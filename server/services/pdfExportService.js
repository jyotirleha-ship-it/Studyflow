import PDFDocument from 'pdfkit';

// 1. Export Single Study Summary
export const buildSummaryPDF = (summary, stream) => {
  const doc = new PDFDocument({ margin: 40 });
  doc.pipe(stream);

  // Header Banner
  doc.rect(40, 40, 532, 60).fill('#4f46e5');
  doc.fillColor('#ffffff').fontSize(22).font('Helvetica-Bold').text('StudyFlow Summary Report', 55, 55);
  doc.fontSize(12).font('Helvetica').text(`Topic: ${summary.topic} | Subject: ${summary.subject || 'General'}`, 55, 82);

  doc.moveDown(3);
  doc.fillColor('#1e293b');

  // Metadata
  doc.fontSize(11).font('Helvetica-Bold').text(`Confidence Score: ${summary.confidenceScore}%`, 40, 120);
  doc.text(`Recommended Next Revision: ${summary.recommendedNextRevision || '48 hours'}`, 320, 120);
  doc.text(`Generated Date: ${new Date(summary.createdAt).toLocaleDateString()}`, 40, 135);

  doc.moveDown(1.5);
  doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(40, 155).lineTo(572, 155).stroke();

  // Section 1: Important Concepts
  let y = 170;
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#4338ca').text('Important Concepts', 40, y);
  y += 22;
  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  (summary.importantConcepts || []).forEach(item => {
    doc.text(`• ${item}`, 50, y);
    y += 18;
  });

  // Section 2: Key Points
  y += 10;
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#4338ca').text('Key Takeaways & Points', 40, y);
  y += 22;
  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  (summary.keyPoints || []).forEach(item => {
    doc.text(`• ${item}`, 50, y);
    y += 18;
  });

  // Section 3: Common Mistakes & Difficult Areas
  y += 10;
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#b91c1c').text('Common Pitfalls & Difficult Areas', 40, y);
  y += 22;
  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  (summary.commonMistakes || []).forEach(item => {
    doc.text(`⚠️ ${item}`, 50, y);
    y += 18;
  });

  // Section 4: Questions to Revise
  y += 10;
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#047857').text('Target Questions for Active Recall', 40, y);
  y += 22;
  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  (summary.questionsToRevise || []).forEach(item => {
    doc.text(`? ${item}`, 50, y);
    y += 18;
  });

  // Footer
  doc.fontSize(8).fillColor('#94a3b8').text('Generated by StudyFlow — Intelligent Study Planner & Personal Learning Mentor', 40, 750, { align: 'center' });

  doc.end();
};

// 2. Export Single Note as PDF
export const buildNotePDF = (note, stream) => {
  const doc = new PDFDocument({ margin: 40 });
  doc.pipe(stream);

  const subjectName = note.subject?.name || 'General Subject';
  const topicName = note.topic?.name || 'General Topic';

  // Header Banner
  doc.rect(40, 40, 532, 60).fill('#0ea5e9');
  doc.fillColor('#ffffff').fontSize(20).font('Helvetica-Bold').text('StudyFlow Study Note', 55, 55);
  doc.fontSize(12).font('Helvetica').text(`${subjectName} • ${topicName}`, 55, 82);

  // Note Metadata
  doc.fillColor('#64748b').fontSize(10).font('Helvetica').text(
    `Created: ${new Date(note.createdAt).toLocaleDateString()} | Last Updated: ${new Date(note.updatedAt).toLocaleDateString()}`,
    40, 115
  );

  doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(40, 135).lineTo(572, 135).stroke();

  // Title
  doc.fillColor('#0f172a').fontSize(16).font('Helvetica-Bold').text(note.title, 40, 150);

  // Tags
  if (note.tags && note.tags.length > 0) {
    doc.fontSize(9).font('Helvetica-Oblique').fillColor('#6366f1').text(
      `Tags: ${note.tags.join(', ')}`,
      40, 175
    );
  }

  // Content
  const contentY = (note.tags && note.tags.length > 0) ? 195 : 175;
  doc.fontSize(11).font('Helvetica').fillColor('#334155').text(
    note.content || '(Empty Note)',
    40, contentY,
    { width: 512, lineGap: 4 }
  );

  // Footer
  doc.fontSize(8).fillColor('#94a3b8').text(
    'Generated by StudyFlow — Personal Knowledge Base & Academic Mentor',
    40, 750,
    { align: 'center' }
  );

  doc.end();
};

// 3. Export All Notes for a Subject as a Notebook PDF
export const buildSubjectNotesPDF = (subject, notes = [], stream) => {
  const doc = new PDFDocument({ margin: 40 });
  doc.pipe(stream);

  const subName = subject?.name || 'Subject';
  const subCode = subject?.code || '';

  // Cover Page Header
  doc.rect(40, 40, 532, 80).fill('#4338ca');
  doc.fillColor('#ffffff').fontSize(24).font('Helvetica-Bold').text(`${subName}`, 55, 55);
  doc.fontSize(13).font('Helvetica').text(`Complete Study Notebook ${subCode ? `(${subCode})` : ''} • ${notes.length} Note(s)`, 55, 88);

  let y = 140;
  doc.fillColor('#1e293b').fontSize(12).font('Helvetica').text(`Exported on ${new Date().toLocaleDateString()}`, 40, y);
  y += 25;

  doc.strokeColor('#cbd5e1').lineWidth(1).moveTo(40, y).lineTo(572, y).stroke();
  y += 20;

  if (notes.length === 0) {
    doc.fillColor('#64748b').fontSize(12).text('No notes have been added to this subject yet.', 40, y);
  } else {
    notes.forEach((note, index) => {
      // If close to page bottom, add new page
      if (y > 650) {
        doc.addPage();
        y = 50;
      }

      doc.fillColor('#4338ca').fontSize(14).font('Helvetica-Bold').text(`${index + 1}. ${note.title}`, 40, y);
      y += 18;

      const topName = note.topic?.name ? `Topic: ${note.topic.name}` : '';
      const updatedStr = `Updated: ${new Date(note.updatedAt).toLocaleDateString()}`;
      doc.fillColor('#64748b').fontSize(9).font('Helvetica').text(`${topName} ${topName ? '| ' : ''}${updatedStr}`, 40, y);
      y += 15;

      doc.fillColor('#334155').fontSize(10).font('Helvetica').text(note.content || '', 40, y, {
        width: 512,
        lineGap: 3
      });

      const noteHeight = doc.heightOfString(note.content || '', { width: 512 });
      y += noteHeight + 25;

      doc.strokeColor('#f1f5f9').lineWidth(1).moveTo(40, y - 10).lineTo(572, y - 10).stroke();
    });
  }

  doc.fontSize(8).fillColor('#94a3b8').text(
    'StudyFlow — Comprehensive Subject Knowledge Base Export',
    40, 750,
    { align: 'center' }
  );

  doc.end();
};

// 4. Export Weekly Progress Report PDF
export const buildWeeklyReportPDF = (user, sessions = [], tasks = [], stream) => {
  const doc = new PDFDocument({ margin: 40 });
  doc.pipe(stream);

  // Header Banner
  doc.rect(40, 40, 532, 60).fill('#059669');
  doc.fillColor('#ffffff').fontSize(22).font('Helvetica-Bold').text('Weekly Study Progress Report', 55, 55);
  doc.fontSize(12).font('Helvetica').text(`Student: ${user.name} | Period: Last 7 Days`, 55, 82);

  const totalMinutes = sessions.reduce((acc, s) => acc + (s.durationMinutes || 0), 0);
  const completedTasks = tasks.filter(t => t.status === 'completed').length;
  const avgFocus = sessions.length > 0
    ? Math.round(sessions.reduce((acc, s) => acc + (s.focusScore || 100), 0) / sessions.length)
    : 100;

  let y = 120;
  doc.fillColor('#1e293b').fontSize(12).font('Helvetica-Bold').text('Executive Summary', 40, y);
  y += 20;

  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  doc.text(`• Total Study Time: ${Math.round(totalMinutes / 60 * 10) / 10} hours (${totalMinutes} minutes)`, 50, y); y += 18;
  doc.text(`• Total Sessions Completed: ${sessions.length}`, 50, y); y += 18;
  doc.text(`• Tasks Completed: ${completedTasks} of ${tasks.length}`, 50, y); y += 18;
  doc.text(`• Average Focus Score: ${avgFocus}%`, 50, y); y += 25;

  doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(40, y).lineTo(572, y).stroke();
  y += 20;

  doc.fontSize(12).font('Helvetica-Bold').fillColor('#059669').text('Recent Study Sessions', 40, y);
  y += 20;

  if (sessions.length === 0) {
    doc.fontSize(10).font('Helvetica').fillColor('#64748b').text('No sessions recorded in this period.', 50, y);
  } else {
    sessions.slice(0, 10).forEach(s => {
      if (y > 700) { doc.addPage(); y = 50; }
      const sessionDate = new Date(s.createdAt).toLocaleDateString();
      const topicStr = s.topic?.name || s.subject?.name || 'Focused Study';
      doc.fontSize(10).font('Helvetica-Bold').fillColor('#1e293b').text(`${sessionDate}: ${topicStr} (${s.durationMinutes} mins) — Focus Score: ${s.focusScore || 100}%`, 50, y);
      y += 16;
      if (s.notes) {
        doc.fontSize(9).font('Helvetica').fillColor('#64748b').text(`Notes: ${s.notes}`, 60, y, { width: 490 });
        y += 18;
      }
    });
  }

  doc.fontSize(8).fillColor('#94a3b8').text('Generated by StudyFlow Analytics & Progress Engine', 40, 750, { align: 'center' });
  doc.end();
};
